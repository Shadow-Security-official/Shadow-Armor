/* Shadow-Armor HTML report. Every value from the report is inserted with
 * textContent (never innerHTML): the page stays safe even when a scanned host
 * returns hostile file names or messages. */
(function () {
  "use strict";
  var R = JSON.parse(document.getElementById("sdw-data").textContent);
  var S = window.ShadowArmorScore;
  var state = { lens: (R.summary && R.summary.lens) || "all", status: "problems", sev: "", pillar: "", q: "", auto: false };
  var STATUS_FILTERS = [["problems", "fail + error + runtime-only"], ["all", "all"], ["fail", "fail"], ["error", "error"],
    ["runtime-only", "runtime-only"], ["pass", "pass"], ["skip", "n/a"], ["waived", "waived"]];
  var SEV_RANK = { critical: 0, high: 1, medium: 2, low: 3, info: 4 };
  var STD_LABEL = { cis: "CIS", anssi: "ANSSI BP-028", nist: "NIST 800-53", nist171: "NIST 800-171", pci: "PCI DSS", stig: "DISA STIG" };
  (R.standards || []).forEach(function (s) { if (s.name) STD_LABEL[s.key] = s.name; });
  var PILLAR = {};
  (R.pillars || []).forEach(function (p) { PILLAR[p.id] = p; });

  function el(tag, cls, text) {
    var e = document.createElement(tag);
    if (cls) e.className = cls;
    if (text !== undefined && text !== null) e.textContent = String(text);
    return e;
  }
  function add(parent) { for (var i = 1; i < arguments.length; i++) if (arguments[i]) parent.appendChild(arguments[i]); return parent; }
  function clear(n) { while (n.firstChild) n.removeChild(n.firstChild); }
  function gcls(g) { return g === "N/A" ? "NA" : g; }
  function fmt(x) { return x === null || x === undefined ? "n/a" : x.toFixed(1); }

  // ---- header -------------------------------------------------------------
  function header() {
    var m = document.getElementById("meta");
    var p = R.target.platform || {};
    var items = [["Target", R.target.uri], ["Platform", (p.name || "") + " " + (p.release || "") + (R.target.container ? " · container " + R.target.container : "")],
      ["Engine", R.engine.name + " " + R.engine.version + " · " + R.engine.mode + " · " + (R.engine.duration_s || 0) + "s"],
      ["Scope", "level " + R.selection.level + " · " + R.selection.count + " controls"],
      ["Generated", R.generated_at]];
    var h = R.target.host;
    if (h && h.boot_id) items.push(["Boot", h.boot_id.slice(0, 8) + (h.booted_at ? " · up since " + h.booted_at : "")]);
    items.forEach(function (it) {
      var s = el("span"); add(s, el("b", null, it[0] + " "), document.createTextNode(it[1])); m.appendChild(s);
    });
    document.title = "Shadow-Armor · " + R.target.uri;
    var f = document.getElementById("footer");
    f.textContent = "Generated by " + R.tool.name + " " + R.tool.version + (R.tool.commit ? " (" + R.tool.commit.slice(0, 12) + ")" : "") +
      " · profile " + R.profile_version + " · report schema " + R.schema + ". Mappings are guidance for evidence collection, not a certification.";
  }

  // ---- summary --------------------------------------------------------------
  function summary(sum) {
    var g = document.getElementById("grade");
    g.className = "grade g-" + gcls(sum.grade);
    g.textContent = sum.grade;
    var sl = document.getElementById("scoreline");
    clear(sl);
    add(sl, document.createTextNode(sum.score === null ? "no evaluated control" : "score " + fmt(sum.score) + " / 100 "),
      el("small", null, "raw grade " + sum.raw_grade + (state.lens !== "all" ? " · lens " + STD_LABEL[state.lens] : "")));
    var caps = document.getElementById("caps");
    clear(caps);
    sum.caps.forEach(function (c) {
      var li = el("li");
      add(li, el("b", null, "capped at " + c.grade + ": "), document.createTextNode(c.reason + " (" + c.ids.slice(0, 6).join(", ") + (c.ids.length > 6 ? " +" + (c.ids.length - 6) : "") + ")"));
      caps.appendChild(li);
    });
    if (sum.qualified_passes && !sum.runtime_qualified && sum.grade === "A") {
      caps.appendChild(el("li", null, sum.qualified_passes + " runtime-only pass(es): the A holds even if they fail after a reboot, so it is not capped."));
    }
    var cn = document.getElementById("counts");
    clear(cn);
    var c = sum.counts;
    [["pass", c.pass, "var(--pass)"], ["reboot-proven", c.reboot_proven, "var(--pass)"], ["runtime-only", c.runtime_only, "var(--rto)"], ["fail", c.fail, "var(--fail)"],
      ["pending", c.pending, "var(--rto)"], ["error", c.error, "var(--error)"], ["n/a", c.skip, "var(--skip)"], ["waived", c.waived, "var(--waived)"]]
      .filter(function (x) { return x[0] !== "reboot-proven" || x[1] > 0; })
      .forEach(function (x) {
        var ch = el("span", "chip"); var dot = el("i"); dot.style.background = x[2];
        add(ch, dot, document.createTextNode(x[0] + " " + x[1])); cn.appendChild(ch);
      });
    radar(sum.pillars);
    pillars(sum.pillars);
  }

  function gradeColor(g) {
    return { A: "var(--a)", B: "var(--b)", C: "var(--c)", D: "var(--d)", E: "var(--e)" }[g] || "var(--na)";
  }

  function radar(ps) {
    var box = document.getElementById("radar");
    clear(box);
    var NS = "http://www.w3.org/2000/svg";
    var size = 300, cx = 150, cy = 150, rad = 105;
    var svg = document.createElementNS(NS, "svg");
    svg.setAttribute("viewBox", "0 0 " + size + " " + size);
    svg.setAttribute("role", "img");
    var byId = {};
    ps.forEach(function (p) { byId[p.id] = p; });
    function pt(i, r) { var a = -Math.PI / 2 + (i * 2 * Math.PI) / 12; return [cx + r * Math.cos(a), cy + r * Math.sin(a)]; }
    [0.25, 0.5, 0.75, 1].forEach(function (f) {
      var poly = document.createElementNS(NS, "polygon");
      var pts = [];
      for (var i = 0; i < 12; i++) pts.push(pt(i, rad * f).join(","));
      poly.setAttribute("points", pts.join(" "));
      poly.setAttribute("fill", "none"); poly.setAttribute("stroke", "var(--line)");
      svg.appendChild(poly);
    });
    var shape = [];
    for (var i = 0; i < 12; i++) {
      var p = byId[i + 1];
      var v = p && p.score !== null ? p.score / 100 : 0;
      shape.push(pt(i, rad * v).join(","));
      var ax = document.createElementNS(NS, "line");
      var end = pt(i, rad);
      ax.setAttribute("x1", cx); ax.setAttribute("y1", cy); ax.setAttribute("x2", end[0]); ax.setAttribute("y2", end[1]);
      ax.setAttribute("stroke", "var(--line)");
      svg.appendChild(ax);
      var lp = pt(i, rad + 16);
      var t = document.createElementNS(NS, "text");
      t.setAttribute("x", lp[0]); t.setAttribute("y", lp[1] + 3); t.setAttribute("text-anchor", "middle");
      t.textContent = String(i + 1).padStart(2, "0") + (p ? " " + p.grade : "");
      svg.appendChild(t);
    }
    var area = document.createElementNS(NS, "polygon");
    area.setAttribute("points", shape.join(" "));
    area.setAttribute("fill", "var(--accent)"); area.setAttribute("fill-opacity", "0.25");
    area.setAttribute("stroke", "var(--accent)"); area.setAttribute("stroke-width", "2");
    svg.appendChild(area);
    var title = document.createElementNS(NS, "title");
    title.textContent = "Score per pillar";
    svg.appendChild(title);
    box.appendChild(svg);
  }

  function pillars(ps) {
    var box = document.getElementById("pillars");
    clear(box);
    ps.forEach(function (p) {
      var meta = PILLAR[p.id] || { title: "Pillar " + p.id, title_fr: "" };
      var card = el("div", "pillar" + (String(state.pillar) === String(p.id) ? " active" : ""));
      card.tabIndex = 0;
      card.setAttribute("role", "button");
      var row = el("div", "row");
      add(row, el("span", "num", String(p.id).padStart(2, "0")), el("span", "g t-" + gcls(p.grade), p.grade));
      var bar = el("div", "bar"); var fill = el("span");
      fill.style.width = (p.score || 0) + "%"; fill.style.background = gradeColor(p.grade); bar.appendChild(fill);
      var ev = p.counts.pass + p.counts.fail + p.counts.error;
      add(card, row, el("div", "title", meta.title), el("div", "fr", meta.title_fr), bar,
        el("div", "small", fmt(p.score) + " · " + p.counts.pass + "/" + ev + " passing" + (p.counts.skip ? " · " + p.counts.skip + " n/a" : "")));
      function pick() { state.pillar = String(state.pillar) === String(p.id) ? "" : String(p.id); document.getElementById("pillarf").value = state.pillar; render(); }
      card.addEventListener("click", pick);
      card.addEventListener("keydown", function (e) { if (e.key === "Enter" || e.key === " ") { e.preventDefault(); pick(); } });
      box.appendChild(card);
    });
  }

  // ---- lens -----------------------------------------------------------------
  function lensBar() {
    var box = document.getElementById("lens");
    clear(box);
    [["all", "All standards"]].concat(Object.keys(STD_LABEL).map(function (k) { return [k, STD_LABEL[k]]; })).forEach(function (l) {
      var b = el("button", null, l[1]);
      b.type = "button";
      b.setAttribute("aria-pressed", state.lens === l[0] ? "true" : "false");
      b.addEventListener("click", function () { state.lens = l[0]; render(); });
      box.appendChild(b);
    });
    var n = R.controls.filter(function (c) { return S.inLens(c, state.lens); }).length;
    document.getElementById("lensnote").textContent = state.lens === "all"
      ? "Every control counts. Pick a standard to grade the host only on the controls that map to it (same formula)."
      : n + " controls map to " + STD_LABEL[state.lens] + "; the grade above is computed on those only.";
  }

  // ---- controls ---------------------------------------------------------------
  function matches(c) {
    if (!S.inLens(c, state.lens)) return false;
    var st = c.status === "pass" && c.qualifier === "runtime-only" ? "runtime-only" : c.status;
    if (state.status === "problems" && !(st === "fail" || st === "error" || st === "runtime-only")) return false;
    if (state.status !== "problems" && state.status !== "all" && st !== state.status) return false;
    if (state.sev && c.severity !== state.sev) return false;
    if (state.pillar && String(c.pillar) !== String(state.pillar)) return false;
    if (state.auto && !(c.remediation && c.remediation.auto)) return false;
    if (state.q) {
      var hay = [c.id, c.title, c.reason, c.rationale].concat((c.evidence || []).map(function (e) { return e.desc + " " + (e.message || ""); }));
      Object.keys(c.map || {}).forEach(function (k) { hay = hay.concat(c.map[k]); });
      if (hay.join(" ").toLowerCase().indexOf(state.q.toLowerCase()) < 0) return false;
    }
    return true;
  }

  function controlRow(c) {
    var d = el("details", "ctl");
    var s = el("summary");
    var qual = c.qualifier ? c.qualifier : "";
    add(s, el("span", "st st-" + c.status, c.status === "skip" ? "n/a" : c.status),
      el("span", "q q-" + qual, qual), el("span", "sev sev-" + c.severity, c.severity));
    var t = el("span"); add(t, el("span", "cid", c.id + " "), el("span", "ctitle", c.title));
    add(s, t, el("span", "fix" + (c.remediation && c.remediation.auto ? " auto" : ""), c.remediation && c.remediation.auto ? "auto-fix" : "manual"));
    d.appendChild(s);
    var body = el("div", "body");
    d.addEventListener("toggle", function once() {
      if (!d.open || body.childNodes.length) return;
      fillBody(body, c);
    });
    d.appendChild(body);
    return d;
  }

  function fillBody(body, c) {
    var pm = PILLAR[c.pillar] || {};
    if (c.reason) add(body, section("Verdict", el("p", null, c.reason)));
    if (c.proof) add(body, section("What this verdict proves", proofGrid(c.proof)));
    if (c.rationale) add(body, section("Why it matters", el("p", null, c.rationale)));
    if (c.check) add(body, section("Effective probe", el("p", null, c.check)));
    if (c.evidence && c.evidence.length) {
      var ul = el("ul", "evidence");
      c.evidence.forEach(function (e) {
        var li = el("li", e.status);
        add(li, el("span", "k", e.kind + " · " + e.status), document.createTextNode(e.desc));
        if (e.message) li.appendChild(el("span", "msg", e.message));
        ul.appendChild(li);
      });
      add(body, section("Evidence", ul));
    }
    var dl = el("dl", "maps");
    add(dl, el("dt", null, "Pillar"), el("dd", null, String(c.pillar).padStart(2, "0") + " · " + (pm.title || "") + (pm.title_fr ? " — " + pm.title_fr : "")));
    add(dl, el("dt", null, "Level · scope"), el("dd", null, "level " + c.level + " · " + (c.scope === "host" ? "host only" : "host and containers")));
    Object.keys(STD_LABEL).forEach(function (k) {
      var refs = S.refs(c.map, k);
      if (!refs.length) return;
      var dd = el("dd");
      refs.forEach(function (r) { dd.appendChild(el("span", "tag", r)); });
      add(dl, el("dt", null, STD_LABEL[k]), dd);
    });
    add(body, section("Mappings", dl));
    var rem = c.remediation || {};
    var rbox = el("div");
    rbox.appendChild(el("p", null, (rem.auto ? "Automatic: " : "Manual: ") + (rem.summary || "")));
    if (rem.risk) rbox.appendChild(el("p", "small", "Risk: " + rem.risk));
    if (rem.reboot) rbox.appendChild(el("p", "small", "Takes full effect after a reboot."));
    if (rem.manual) rbox.appendChild(el("p", null, rem.manual));
    if (rem.auto) rbox.appendChild(el("pre", "cmd", "sdw-armor harden " + R.target.uri + " --rules " + c.id));
    add(body, section("Remediation", rbox));
    if (c.waiver) add(body, section("Waiver", el("p", null, (c.waiver.justification || "") + (c.waiver.expires ? " (expires " + c.waiver.expires + ")" : ""))));
    if (c.source) body.appendChild(el("p", "small", "Control source: " + c.source));
  }

  var PROOF_TEXT = {
    proven: ["✓", "proven"], failed: ["✗", "failed"], not_measured: ["?", "not measured"], "n/a": ["–", "not applicable"],
    expected: ["✓", "expected: the persisted state is compliant"], lost: ["✗", "lost at the last reboot"]
  };
  function proofGrid(pr) {
    var g = el("div", "proof");
    [["Running now", pr.now], ["On disk", pr.on_disk], ["After a reboot", pr.reboot]].forEach(function (col, i) {
      var v = col[1] || "not_measured";
      var t = PROOF_TEXT[v] || ["?", v];
      var label = i === 2 && v === "proven" ? "proven: survived a real reboot" : i === 2 && v === "failed" ? "would be undone: the persisted state is not compliant" : t[1];
      if (i === 2 && v === "n/a") label = "not applicable: a reboot clears this state";
      var cell = el("div", "pc pc-" + v.replace("/", ""));
      add(cell, el("span", "pk", col[0]), el("span", "pv", t[0] + " " + label));
      g.appendChild(cell);
    });
    return g;
  }

  function section(label, node) {
    var d = el("div");
    add(d, el("div", "label", label), node);
    return d;
  }

  function controls() {
    var box = document.getElementById("controls");
    clear(box);
    var list = R.controls.filter(matches).sort(function (a, b) {
      var order = { fail: 0, error: 1, pass: 2, waived: 3, skip: 4 };
      var ra = a.status === "pass" && a.qualifier === "runtime-only" ? 1.5 : order[a.status];
      var rb = b.status === "pass" && b.qualifier === "runtime-only" ? 1.5 : order[b.status];
      if (ra !== rb) return ra - rb;
      if (SEV_RANK[a.severity] !== SEV_RANK[b.severity]) return SEV_RANK[a.severity] - SEV_RANK[b.severity];
      return a.id < b.id ? -1 : 1;
    });
    if (!list.length) { box.appendChild(el("div", "empty", "No control matches these filters.")); return; }
    var frag = document.createDocumentFragment();
    list.forEach(function (c) { frag.appendChild(controlRow(c)); });
    box.appendChild(frag);
  }

  function filters() {
    var sf = document.getElementById("statusf");
    clear(sf);
    STATUS_FILTERS.forEach(function (f) {
      var b = el("button", null, f[1]);
      b.type = "button";
      b.setAttribute("aria-pressed", state.status === f[0] ? "true" : "false");
      b.addEventListener("click", function () { state.status = f[0]; render(); });
      sf.appendChild(b);
    });
  }

  function render() {
    var sum = S.compute(R.controls, R.weights, state.lens);
    summary(sum);
    lensBar();
    filters();
    controls();
  }

  function init() {
    header();
    var pf = document.getElementById("pillarf");
    (R.pillars || []).forEach(function (p) { var o = el("option", null, String(p.id).padStart(2, "0") + " " + p.title); o.value = String(p.id); pf.appendChild(o); });
    pf.addEventListener("change", function () { state.pillar = pf.value; render(); });
    document.getElementById("sevf").addEventListener("change", function (e) { state.sev = e.target.value; render(); });
    document.getElementById("autof").addEventListener("change", function (e) { state.auto = e.target.checked; render(); });
    var qt;
    document.getElementById("q").addEventListener("input", function (e) {
      clearTimeout(qt); qt = setTimeout(function () { state.q = e.target.value.trim(); controls(); }, 150);
    });
    document.getElementById("theme").addEventListener("click", function () {
      var root = document.documentElement;
      var dark = root.getAttribute("data-theme") ? root.getAttribute("data-theme") === "dark" : window.matchMedia("(prefers-color-scheme: dark)").matches;
      root.setAttribute("data-theme", dark ? "light" : "dark");
    });
    render();
  }
  init();
})();
